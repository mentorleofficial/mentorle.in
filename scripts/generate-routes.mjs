// Lists every static page route in src/app and writes src/lib/seo/app-routes.generated.ts, which the sitemap reads.
// Runs before `npm run dev` and `npm run build`, so a new page is in the sitemap without anyone editing a list.
// Pages with a dynamic segment ([slug]) come from the database instead (mentors, events). Route groups "(name)" are
// left out of the URL; parallel slots (@auth), intercepted routes ("(.)login") and private folders (_name) aren't
// pages of their own and are skipped.
//
//   node scripts/generate-routes.mjs           write the file
//   node scripts/generate-routes.mjs --check   fail if it's out of date (part of `npm run lint`)

import { readdirSync, readFileSync, writeFileSync, existsSync } from "node:fs";
import { join, relative, sep } from "node:path";

const APP = join(process.cwd(), "src", "app");
const OUT = join(process.cwd(), "src", "lib", "seo", "app-routes.generated.ts");
const PAGE = /^page\.(tsx|ts|jsx|js|mdx)$/;

function walk(dir, found = []) {
  for (const entry of readdirSync(dir, { withFileTypes: true })) {
    if (entry.isDirectory()) {
      const name = entry.name;
      if (name.startsWith("@") || name.startsWith("_") || name.startsWith("(.") || /^\(\.+\)/.test(name)) continue;
      walk(join(dir, name), found);
    } else if (PAGE.test(entry.name)) {
      found.push(dir);
    }
  }
  return found;
}

const routes = walk(APP)
  .map((dir) => relative(APP, dir).split(sep).filter(Boolean))
  .filter((segments) => !segments.some((segment) => segment.startsWith("[")))
  .map((segments) => "/" + segments.filter((segment) => !/^\(.*\)$/.test(segment)).join("/"))
  .filter((route, index, all) => all.indexOf(route) === index)
  .sort((a, b) => (a === "/" ? -1 : b === "/" ? 1 : a.localeCompare(b)));

const source = `// Generated by scripts/generate-routes.mjs (runs before dev and build). Don't edit by hand.
// Every static page route in src/app; src/app/sitemap.ts filters out the private ones (src/lib/seo/routes.ts).
export const APP_ROUTES = ${JSON.stringify(routes, null, 2)} as const;
`;

const current = existsSync(OUT) ? readFileSync(OUT, "utf8") : "";
if (process.argv.includes("--check")) {
  if (current.replace(/\r\n/g, "\n") !== source) {
    console.error("src/lib/seo/app-routes.generated.ts is out of date: run `node scripts/generate-routes.mjs`.");
    process.exit(1);
  }
} else if (current !== source) {
  writeFileSync(OUT, source);
  console.log(`Routes: ${routes.length} static pages written to src/lib/seo/app-routes.generated.ts`);
}
